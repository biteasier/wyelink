    @Test
    public void everySignInLinkGoesToBrowser1() {
        List<String> missed = new ArrayList<>();
        for (String url : SIGN_IN) {
            if (Router.decide(new Router.Config(), url, null, false).target != Router.BROWSER_1) missed.add(url);
        }
        assertTrue("Missed sign-in links:\n" + String.join("\n", missed), missed.isEmpty());
    }

    @Test
    public void everyOrdinaryLinkGoesToBrowser2() {
        List<String> wrong = new ArrayList<>();
        for (String url : ORDINARY) {
            Router.Decision d = Router.decide(new Router.Config(), url, null, false);
            if (d.target != Router.BROWSER_2) wrong.add(url + "  [" + d.reason + "]");
        }
        assertTrue("Ordinary links sent to Browser 1:\n" + String.join("\n", wrong), wrong.isEmpty());
    }
